-- Lesson 7.2: What Forgiveness Is NOT
UPDATE public.course_lessons
SET content_body = '# What Forgiveness Is NOT

Mistaking forgiveness for relational access leads to repeated vulnerability and harm.

* **Forgiveness is NOT Denial**: It does not say, "It wasn''t a big deal." True forgiveness must state the exact truth: "What you did was wrong, it hurt me, and yet I release the right to punish you."
* **Forgiveness is NOT Silence**: Forgiveness does not require you to keep secrets for an instigator. Telling the truth is an act of love and safety.
* **Forgiveness is NOT Immediate Trust**: Trust is earned slowly through consistent behavior over time. Forgiving someone does not mean you immediately hand back your safety.
* **Forgiveness is NOT Reconciliation**: Reconciliation requires two people to be in agreement and safety. You can forgive someone from a distance while keeping a firm, protective boundary in place.

