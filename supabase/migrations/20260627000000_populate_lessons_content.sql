### Action Plan:
1. **Document Everything**: Use a systematic tracking log (Date, Time, Location, Incident details, Witnesses, Evidence).
2. **Engage Authority**: Schedule a formal, calm conversation with the school teacher, principal, youth pastor, or group leader. Present your objective log.
3. **Set Relational Rest**: Give your child permission to step away from the specific environment or group temporarily if needed.'
