-- Lesson 4.3: Exit Scripts
UPDATE public.course_lessons
SET content_body = '# Exit Scripts: "I''m walking away."

An exit script gives the child a verbal bridge to leave the situation immediately. It ensures they exit on their own terms without arguing or trying to win a fight.

### Rules for Exits:
* Say your line clearly, turn immediately, and walk toward a safe, populated area.
* Do not wait around to see how the other person reacts.
* Do not look back.

### Word-for-Word Exit Scripts:
* "I''m walking away now."
* "I have somewhere else to be. Bye."
* "I''m not going to stand here and listen to this."
* "I''m going to go join the other group."'
