-- Lesson 4.4: Practice Without Pressure
UPDATE public.course_lessons
SET content_body = '# Practice Without Pressure: Help-Seeking & Roleplay

Many children hesitate to seek help because they don''t want to be called a "tattletale." Teach your child the difference between tattling (trying to get someone in trouble for a minor infraction) and reporting (protecting safety and boundaries).

### Word-for-Word Reporting Scripts:
* "I need help. [Name] is repeatedly crossing my boundaries, and I''ve asked them to stop."
* "I am feeling unsafe. I need you to step in."
* "Can you please help me? I''m trying to walk away and [Name] is blocking me."
* "I am reporting this because it''s not safe."

### Parent-Child Practice Roleplay Guide:

**Exercise 1: The "Mirror Mirror" (Posture Check)**
1. Stand in front of your child.
2. Ask them to practice standing with "courage posture": shoulders back, head up, hands relaxed, feet slightly apart.
3. Have them say their boundary script (*"Stop. I don''t like that."*) while holding that posture for 5 seconds. Praise their strong posture!

**Exercise 2: The "Say and Go" (Exit Practice)**
1. You act as the mild instigator (e.g., saying something slightly silly or teasing in a playful way, like *"Hey, you can''t play here"*).
2. Have your child say their exit line (*"I''m walking away now."*).
3. Have them immediately turn and walk to the other side of the room.
4. High-five them and celebrate their successful exit!

**Exercise 3: The "Tattling vs. Reporting" Game**
Read these scenarios to your child and ask them: *"Is this tattling, or is this reporting?"*
* **Scenario A**: *"Joey took the blue crayon when I wanted to use it."* -> **Tattling**
* **Scenario B**: *"Sarah keeps calling me mean names on the bus every single day, and it makes my stomach hurt."* -> **Reporting**
* **Scenario C**: *"Tommy fell off the swings and hit his knee, and he is crying."* -> **Reporting**'
