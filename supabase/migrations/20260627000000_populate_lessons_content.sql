In many faith communities, children and parents facing mistreatment are rushed to forgive. While forgiveness is a central pillar of Christian faith, a rushed, superficial application of it can act as "spiritual duct tape." It silences the victim, enables the wrongdoer, and hides truth.

Forgiveness is an internal transaction between you and God. It is the conscious decision to release the debt of vengeance to Him.

