-- Lesson 4.2: Boundary Scripts
UPDATE public.course_lessons
SET content_body = '# Boundary Scripts: "Stop. I don''t like that."

A boundary script is designed to establish a clear, firm, non-defensive wall. It does not trade insults or argue—it simply states truth.

### Rules for Boundaries:
* Keep your back straight and look the other person in the eye.
* Speak in a strong, normal talking voice (do not shout or whisper).
* Keep your hands relaxed by your sides.

### Word-for-Word Boundary Scripts:
* "Stop. I don''t like that."
* "That is not okay. Stop doing that."
* "Please don''t speak to me that way."
* "We are not doing this. Stop."'
