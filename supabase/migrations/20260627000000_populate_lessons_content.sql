UPDATE public.course_lessons
SET content_body = '# The 9 Emotions of Bullying

Bullying triggers a complex web of emotions. We categorize these into nine key emotions:

1. **Sad:** Grief over lost friendships or safety.
2. **Anxious:** Dread of going back to the school or social environment.
3. **Frustrated:** Feeling helpless to stop the mistreatment.
4. **Troubled:** Deep internal disturbance or confusion.
5. **Afraid:** Fear of physical or social harm.
6. **Angry:** Resentment and desire for justice or revenge.
7. **Ashamed:** Believing that they are targeted because something is wrong with them.
8. **Confused:** Struggling to understand why they are being singled out.
9. **Lonely:** Feeling isolated and that no one understands.

Helping your child map their experience to these specific words makes their pain manageable and helps you select the right response.'
