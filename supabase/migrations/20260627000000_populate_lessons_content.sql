* **Entrusting Justice to God**: Forgiveness does not mean pretending that a wrong was righted; it means transferring the case from your personal courtroom to God''s ultimate courtroom.
* **An Act of Freedom**: You forgive to release your heart from bitterness, so your spiritual growth is not blocked by another person''s actions.'
