-- Lesson 6.2: Yellow: Document & Involve Adults
UPDATE public.course_lessons
SET content_body = '# 🟡 Yellow Level: Document & Involve Adults

Yellow level situations represent relational harm that has transitioned from normal friction into systemic mistreatment or repeated harassment.

### Indicators:
* **Repetition**: The behavior is ongoing (happening multiple times a week).
* **Power Imbalance**: The instigator is older, larger, holds high social power, or coordinates group exclusion.
* **Child Distress**: The child shows physical indicators of distress (headaches, stomach aches, refusing school/youth group, bedwetting, or withdrawal).
